-- ThreatDesk Snowflake Setup Script

-- 1. Warehouse
CREATE WAREHOUSE IF NOT EXISTS THREAT_WH
  WITH WAREHOUSE_SIZE = 'X-SMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

-- 2. Database and Schema
CREATE DATABASE IF NOT EXISTS THREAT_DB;
CREATE SCHEMA IF NOT EXISTS THREAT_DB.THREAT_SCHEMA;

USE DATABASE THREAT_DB;
USE SCHEMA THREAT_SCHEMA;
USE WAREHOUSE THREAT_WH;

-- 3. Read-only Role
CREATE ROLE IF NOT EXISTS THREAT_ANALYST;

-- 4. Grants
GRANT USAGE ON WAREHOUSE THREAT_WH TO ROLE THREAT_ANALYST;
GRANT USAGE ON DATABASE THREAT_DB TO ROLE THREAT_ANALYST;
GRANT USAGE ON SCHEMA THREAT_DB.THREAT_SCHEMA TO ROLE THREAT_ANALYST;
GRANT SELECT ON ALL TABLES IN SCHEMA THREAT_DB.THREAT_SCHEMA TO ROLE THREAT_ANALYST;
GRANT SELECT ON FUTURE TABLES IN SCHEMA THREAT_DB.THREAT_SCHEMA TO ROLE THREAT_ANALYST;
